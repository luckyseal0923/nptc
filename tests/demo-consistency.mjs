import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { transpileModule, ScriptTarget, ModuleKind } from 'typescript';
const hospitals=JSON.parse(readFileSync('public/data/accredited-hospitals.json','utf8'));
let source=transpileModule(readFileSync('lib/demo.ts','utf8'),{compilerOptions:{target:ScriptTarget.ES2022,module:ModuleKind.ESNext}}).outputText;
const originalFetch=globalThis.fetch;
globalThis.fetch=async()=>({ok:true,json:async()=>structuredClone(hospitals)});
for(const name of ['domains','grading','schema'])source=source.replaceAll(`'./${name}'`,()=>JSON.stringify(pathToFileURL(resolve(`lib/${name}.ts`)).href));
const storage=new Map();globalThis.localStorage={getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value),removeItem:key=>storage.delete(key)};
const {demoRpc,signInDemo}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
signInDemo('teacher','teacher','demo1234');
const current=(await demoRpc('nptc_teacher_data')).selected;
await assert.rejects(()=>demoRpc('nptc_teacher_write',{body:{action:'deleteStudent',workshopId:current.id,id:'demo-student',revision:0}}),/所有題目公告/);
await assert.rejects(()=>demoRpc('nptc_teacher_write',{body:{action:'saveScores',workshopId:current.id}}),/五面向/);
await assert.rejects(()=>demoRpc('nptc_teacher_save_stations_v3',{body:{workshopId:current.id,stationsRevision:0,stations:current.stations.map(s=>({...s,title:'竄改'}))}}),/撤回本題/);
const request={action:'createWorkshop',name:'重試梯次',requestId:'30000000-0000-0000-0000-000000000001'};
assert.deepEqual(await demoRpc('nptc_teacher_write',{body:request}),await demoRpc('nptc_teacher_write',{body:request}));
for(const station of current.stations)await demoRpc('nptc_teacher_publish_station',{body:{workshopId:current.id,station:station.key,published:false}});
const body={workshopId:current.id,stationsRevision:4,stations:current.stations};
await demoRpc('nptc_teacher_save_stations_v3',{body});
await assert.rejects(()=>demoRpc('nptc_teacher_save_stations_v3',{body}),/重新載入/);
assert.equal((await demoRpc('nptc_analysis_data')).includesArchived,false);
signInDemo('student','student','demo1234');
await assert.rejects(()=>demoRpc('nptc_teacher_data'),/老師權限/);
await assert.rejects(()=>demoRpc('nptc_student_update_profile',{body:{nursingYears:0,hospital:'任意醫院',unit:'內科',examSpecialty:'內科',firstOsce:false,birthDate:'1990-01-01'}}),/官方醫院/);
assert.equal((await demoRpc('nptc_student_data')).records[0].profile.hospital,'');
delete globalThis.localStorage;
globalThis.fetch=originalFetch;
console.log('PASS: demo publication, roster lock, no legacy bypass, station revisions, create retries, roles and official hospital validation');
