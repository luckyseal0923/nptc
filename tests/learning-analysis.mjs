import assert from 'node:assert/strict';
import {analysisFixture} from './analysis-fixture.mjs';
import {enrollments,statistics,distribution,learners,timeline,background,loadAnalysis,identityKey} from '../lib/learning-analysis.ts';
const rows=enrollments(analysisFixture), exams=rows.flatMap(r=>r.exams);
assert.equal(rows.length,5);
assert.equal(learners(rows).length,4,'same email merges; same name with different email does not');
const stats=statistics(exams);
assert.deepEqual(stats,{total:8,scored:5,missing:3,mean:65,comparable:4,passed:3,passRate:75});
assert.equal(statistics(rows[0].exams).mean,30,'zero is a score, null is not');
assert.equal(statistics([]).mean,null);
assert.equal(statistics([{score:70,threshold:null}]).passRate,null);
assert.deepEqual(distribution(exams).map(d=>d.count),[1,1,1,0,2]);
assert.equal(distribution([{score:59.5}])[0].count,1);
assert.equal(background(rows[0].student,'first_osce'),'非首次報考');
assert.equal(background(rows[0].student,'nursing_years'),'未滿 5 年');
assert.equal(background(rows[2].student,'first_osce'),'未填寫');
const history=timeline(rows,rows[0].identity);
assert.equal(history.length,3);
assert.deepEqual(history.map(e=>e.date),['2026-01-10','2026-01-11','2026-02-10']);
assert.equal(history[0].threshold,60);
assert.equal(history[2].threshold,80,'same station key must retain workshop-specific threshold');
assert.equal(history[2].feedback,'持續練習整合評估與表達。');
assert.notEqual(identityKey({id:'a',email:''}),identityKey({id:'b',email:''}));
assert.equal((await loadAnalysis(async id=>analysisFixture.find(d=>d.selected.id===(id??'w1')))).length,2);
await assert.rejects(()=>loadAnalysis(async id=>{if(id)throw Error('offline');return analysisFixture[0];}),/offline/);
await assert.rejects(()=>loadAnalysis(async ()=>analysisFixture[0]),/梯次資料已變動/);
assert.deepEqual(await loadAnalysis(async()=>({selected:null,workshops:[],students:[],thresholds:[]})),[]);
console.log('PASS: denominators, zero/null, thresholds per workshop, identities, history, background groups, empty state, atomic loading');
